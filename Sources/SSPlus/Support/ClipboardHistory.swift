import AppKit
import Combine
import CryptoKit
import ImageIO

// MARK: - Girdi

/// Pano geçmişindeki tek bir kopyalama. Görüntüler tam çözünürlükte diske,
/// küçük önizlemeleri belleğe alınır; metinler doğrudan manifestte saklanır.
struct ClipboardEntry: Identifiable, Equatable, Codable {
    enum Kind: String, Codable {
        case text
        case image
    }

    let id: UUID
    let kind: Kind
    let date: Date
    /// kind == .text: metnin kendisi (uzunluğu sınırlanır)
    var text: String?
    /// kind == .image: kayıt klasöründeki görüntü dosyasının adı
    var imageFile: String?
}

// MARK: - Depo

/// Sistem panosunu izler ve son kopyalamaları arşivler.
///
/// Geçmiş **isteğe bağlıdır** (`SettingsStore.clipboardHistoryEnabled`,
/// varsayılan kapalı): kopyalanan her şey diske yazıldığı için kullanıcı
/// bilerek açar. Şifre yöneticileri gibi uygulamaların gizli/geçici olarak
/// işaretlediği içerik (`org.nspasteboard.ConcealedType` / `TransientType` /
/// `AutoGeneratedType`) hiçbir zaman arşive ALINMAZ.
///
/// SS+'ın kendi kopyaladığı ekran görüntüleri de arşive düşer — ada ve menü
/// paneli son yakalamalara buradan erişir. Bunlar `noteOwnCapture` ile ZATEN
/// kodlanmış veriden yazılır; ana iş parçacığında yeniden PNG üretilmez.
/// Yabancı görüntülerin kodlanması da arka planda yapılır.
@MainActor
final class ClipboardStore: ObservableObject {
    static let shared = ClipboardStore()

    @Published private(set) var entries: [ClipboardEntry] = []

    /// Arayüzde gösterilen küçük önizlemeler (bellekte).
    private var thumbnails: [UUID: NSImage] = [:]

    private var lastChangeCount: Int
    /// Son arşivlenen görüntünün özeti: aynı görüntü art arda düşmesin.
    private var lastImageDigest: SHA256Digest?
    private var timer: Timer?
    private var cancellables = Set<AnyCancellable>()

    static let maxEntries = 10
    private static let maxTextLength = 5000
    private static let thumbnailEdge: CGFloat = 192

    private static let skippedTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    /// ~/Library/Application Support/SSPlus/Clipboard
    let storeDirectory: URL = {
        let base = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask).first!
        return base.appendingPathComponent("SSPlus/Clipboard", isDirectory: true)
    }()

    private var manifestURL: URL {
        storeDirectory.appendingPathComponent("manifest.json")
    }

    var isEnabled: Bool { SettingsStore.shared.clipboardHistoryEnabled }

    private init() {
        lastChangeCount = NSPasteboard.general.changeCount
        load()
    }

    /// AppDelegate açılışta bir kez çağırır; ayar açıksa izleme başlar ve
    /// ayar değiştikçe açılıp kapanır.
    func start() {
        applyEnabledState()
        SettingsStore.shared.$clipboardHistoryEnabled
            .dropFirst()
            .receive(on: DispatchQueue.main)
            .sink { [weak self] _ in
                MainActor.assumeIsolated { self?.applyEnabledState() }
            }
            .store(in: &cancellables)
    }

    private func applyEnabledState() {
        if isEnabled {
            guard timer == nil else { return }
            lastChangeCount = NSPasteboard.general.changeCount   // açılış anındaki içerik alınmaz
            let timer = Timer(timeInterval: 0.75, repeats: true) { [weak self] _ in
                Task { @MainActor in self?.poll() }
            }
            RunLoop.main.add(timer, forMode: .common)
            self.timer = timer
        } else {
            timer?.invalidate()
            timer = nil
        }
    }

    // MARK: İzleme

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        let types = pasteboard.types ?? []
        // Gizli / geçici (şifre yöneticisi vb.) içerik arşivlenmez
        if types.contains(where: Self.skippedTypes.contains) { return }

        // Yalnızca gerçek görüntü verisi; Finder'da kopyalanan dosya URL'leri
        // (kocaman PSD/TIFF) burada çözülmez.
        if types.contains(.png), let data = pasteboard.data(forType: .png) {
            archiveForeignImage(data, isPNG: true)
            return
        }
        if types.contains(.tiff), let data = pasteboard.data(forType: .tiff) {
            archiveForeignImage(data, isPNG: false)
            return
        }

        if let raw = pasteboard.string(forType: .string) {
            let text = raw.trimmingCharacters(in: .whitespacesAndNewlines)
            if !text.isEmpty {
                add(text: String(text.prefix(Self.maxTextLength)))
            }
        }
    }

    private func add(text: String) {
        // Aynı içerik varsa en üste taşı (kopya üretme)
        entries.removeAll { $0.kind == .text && $0.text == text }
        entries.insert(ClipboardEntry(id: UUID(), kind: .text, date: Date(), text: text, imageFile: nil), at: 0)
        trim()
        save()
    }

    /// Başka bir uygulamadan gelen görüntü: özet, PNG dönüşümü, dosya yazımı ve
    /// küçük önizleme ARKA PLANDA; yalnızca listeye ekleme ana aktörde.
    private func archiveForeignImage(_ data: Data, isPNG: Bool) {
        let digest = SHA256.hash(data: data)
        guard digest != lastImageDigest else { return }
        lastImageDigest = digest
        guard data.count >= 64 else { return }

        let directory = storeDirectory
        let edge = Self.thumbnailEdge
        let changeCount = lastChangeCount
        Task.detached(priority: .utility) {
            let png: Data
            if isPNG {
                png = data
            } else {
                guard let rep = NSBitmapImageRep(data: data),
                      rep.pixelsWide >= 16, rep.pixelsHigh >= 16,
                      let encoded = rep.representation(using: .png, properties: [:]) else { return }
                png = encoded
            }
            guard let written = Self.writeFile(png, fileExtension: "png", in: directory),
                  let thumb = Self.makeThumbnail(from: png, edge: edge) else { return }
            await MainActor.run {
                // Bu arada pano yine değiştiyse eski görüntüyü yine de kaydet;
                // sırası tarihine göre doğru kalır.
                _ = changeCount
                ClipboardStore.shared.insertImage(fileName: written, thumbnail: thumb)
            }
        }
    }

    /// SS+'ın kendi yakalaması: `OutputPipeline` zaten PNG/JPEG üretti, onu
    /// olduğu gibi kaydet. Pano sayacı ilerletilir ki `poll` aynı görüntüyü
    /// bir de kendisi kodlamasın.
    func noteOwnCapture(encoded data: Data, fileExtension: String, pasteboardChangeCount: Int) {
        lastChangeCount = pasteboardChangeCount
        lastImageDigest = SHA256.hash(data: data)
        guard isEnabled else { return }

        let directory = storeDirectory
        let edge = Self.thumbnailEdge
        Task.detached(priority: .utility) {
            guard let written = Self.writeFile(data, fileExtension: fileExtension, in: directory),
                  let thumb = Self.makeThumbnail(from: data, edge: edge) else { return }
            await MainActor.run {
                ClipboardStore.shared.insertImage(fileName: written, thumbnail: thumb)
            }
        }
    }

    /// SS+'ın kendi yazdığı metin (örn. Drive paylaşım linki) geçmişe yabancı
    /// bir kopya olarak düşmesin.
    func markOwnChange(_ pasteboardChangeCount: Int) {
        lastChangeCount = pasteboardChangeCount
    }

    private func insertImage(fileName: String, thumbnail: NSImage) {
        let entry = ClipboardEntry(id: UUID(), kind: .image, date: Date(), text: nil, imageFile: fileName)
        thumbnails[entry.id] = thumbnail
        entries.insert(entry, at: 0)
        trim()
        save()
    }

    private func trim() {
        guard entries.count > Self.maxEntries else { return }
        let removed = entries[Self.maxEntries...]
        entries = Array(entries.prefix(Self.maxEntries))
        for entry in removed {
            thumbnails.removeValue(forKey: entry.id)
            if let file = entry.imageFile {
                try? FileManager.default.removeItem(at: storeDirectory.appendingPathComponent(file))
            }
        }
    }

    // MARK: Erişim

    /// Listelerde gösterilen küçük görüntü.
    func thumbnail(for entry: ClipboardEntry) -> NSImage? {
        guard entry.kind == .image, let file = entry.imageFile else { return nil }
        if let cached = thumbnails[entry.id] { return cached }
        guard let data = try? Data(contentsOf: storeDirectory.appendingPathComponent(file)),
              let thumb = Self.makeThumbnail(from: data, edge: Self.thumbnailEdge) else { return nil }
        thumbnails[entry.id] = thumb
        return thumb
    }

    /// Öğeyi panoya geri yazar.
    func recopy(_ entry: ClipboardEntry) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        switch entry.kind {
        case .text:
            pasteboard.setString(entry.text ?? "", forType: .string)
        case .image:
            guard let file = entry.imageFile,
                  let data = try? Data(contentsOf: storeDirectory.appendingPathComponent(file)) else { return }
            OutputPipeline.writeImageToPasteboard(data, fileExtension: (file as NSString).pathExtension)
        }
        // Geri kopyalama yeni bir girdi üretmesin
        lastChangeCount = pasteboard.changeCount
    }

    /// Pazarlama ekran görüntüsü için bellekte örnek pano. Manifest'e yazılmaz.
    func installExportFixtures() {
        func swatch(_ r: CGFloat, _ g: CGFloat, _ b: CGFloat) -> NSImage {
            let img = NSImage(size: NSSize(width: 192, height: 128))
            img.lockFocus()
            NSColor(srgbRed: r, green: g, blue: b, alpha: 1).setFill()
            NSBezierPath(rect: NSRect(origin: .zero, size: img.size)).fill()
            img.unlockFocus()
            return img
        }
        let a = UUID(), b = UUID(), c = UUID()
        thumbnails[a] = swatch(1, 0.36, 0.62)
        thumbnails[b] = swatch(0.62, 0.34, 0.98)
        thumbnails[c] = swatch(0.12, 0.14, 0.22)
        entries = [
            ClipboardEntry(id: a, kind: .image, date: Date(), text: nil, imageFile: "export-a.png"),
            ClipboardEntry(id: UUID(), kind: .text, date: Date().addingTimeInterval(-40), text: "⌃⌘– ile yakala, yerinde çiz, kaybol.", imageFile: nil),
            ClipboardEntry(id: b, kind: .image, date: Date().addingTimeInterval(-80), text: nil, imageFile: "export-b.png"),
            ClipboardEntry(id: UUID(), kind: .text, date: Date().addingTimeInterval(-120), text: "Son 10 kopya adada ve menü panelinde.", imageFile: nil),
            ClipboardEntry(id: c, kind: .image, date: Date().addingTimeInterval(-180), text: nil, imageFile: "export-c.png"),
            ClipboardEntry(id: UUID(), kind: .text, date: Date().addingTimeInterval(-240), text: "https://ssplus.app", imageFile: nil),
        ]
    }

    func clear() {
        for entry in entries where entry.kind == .image {
            if let file = entry.imageFile {
                try? FileManager.default.removeItem(at: storeDirectory.appendingPathComponent(file))
            }
        }
        entries.removeAll()
        thumbnails.removeAll()
        save()
    }

    // MARK: Kalıcılık

    private func save() {
        try? FileManager.default.createDirectory(at: storeDirectory, withIntermediateDirectories: true)
        guard let data = try? JSONEncoder().encode(entries) else { return }
        try? data.write(to: manifestURL, options: .atomic)
    }

    private func load() {
        guard let data = try? Data(contentsOf: manifestURL),
              let stored = try? JSONDecoder().decode([ClipboardEntry].self, from: data) else { return }
        // Diskte kalmayan görüntüleri at
        entries = stored.filter { entry in
            guard entry.kind == .image else { return true }
            guard let file = entry.imageFile else { return false }
            return FileManager.default.fileExists(atPath: storeDirectory.appendingPathComponent(file).path)
        }
        entries = Array(entries.prefix(Self.maxEntries))
    }

    // MARK: Arka plan yardımcıları (aktör dışı)

    private nonisolated static func writeFile(_ data: Data, fileExtension: String, in directory: URL) -> String? {
        let name = UUID().uuidString + "." + fileExtension
        try? FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        guard (try? data.write(to: directory.appendingPathComponent(name), options: .atomic)) != nil else { return nil }
        return name
    }

    /// Küçültülmüş çözümleme: dosyanın tamamını çözmeden, ImageIO ile.
    private nonisolated static func makeThumbnail(from data: Data, edge: CGFloat) -> NSImage? {
        guard let source = CGImageSourceCreateWithData(data as CFData, nil) else { return nil }
        let options: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceThumbnailMaxPixelSize: Int(edge * 2),   // Retina için 2x
            kCGImageSourceCreateThumbnailWithTransform: true,
        ]
        guard let cg = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary) else { return nil }
        let scale = max(1, CGFloat(max(cg.width, cg.height)) / edge)
        return NSImage(cgImage: cg, size: NSSize(width: CGFloat(cg.width) / scale, height: CGFloat(cg.height) / scale))
    }
}

// MARK: - NSImage yardımcıları

extension NSImage {
    /// En uzun kenarı `edge` olacak şekilde küçültülmüş kopya.
    func downscaled(to edge: CGFloat) -> NSImage {
        let size = size
        guard size.width > 0, size.height > 0 else { return self }
        let scale = min(edge / size.width, edge / size.height)
        guard scale < 1 else { return self }
        let target = NSSize(width: floor(size.width * scale), height: floor(size.height * scale))
        let scaled = NSImage(size: target)
        scaled.lockFocus()
        NSGraphicsContext.current?.imageInterpolation = .high
        draw(in: NSRect(origin: .zero, size: target), from: .zero, operation: .sourceOver, fraction: 1)
        scaled.unlockFocus()
        return scaled
    }

    func pngData() -> Data? {
        guard let tiff = tiffRepresentation,
              let rep = NSBitmapImageRep(data: tiff) else { return nil }
        return rep.representation(using: .png, properties: [:])
    }
}
